/**
 * Windows 드라이브 경로를 판정하는 정규식 두 개입니다. 두 정규식 모두 드라이브 문자 하나와 `:`로 시작하고
 * 대소문자를 가리지 않으며, 구분자 범위가 다른 것은 쓰는 곳의 목적이 다르기 때문입니다.
 */

/**
 * 드라이브 문자 뒤에 구분자까지 있어야 경로로 봅니다. `x:y` 같은 한 글자 scheme의 URL과 드라이브 상대
 * 경로(`C:a.md`)는 경로가 아니므로 그대로 둡니다. 주소를 로컬 파일로 열지 가릴 때 씁니다.
 */
export const WINDOWS_DRIVE_PATH = /^[a-z]:[\\/]/i;

/**
 * CommonMark는 링크 주소에서 문장부호 앞 `\`만 escape로 지우고 `/`는 그대로 두므로, 파싱 결과가 원문과
 * 달라지는 것은 역슬래시로 시작하는 드라이브 경로뿐입니다. 원문 주소에서 지워진 `\`를 되살릴 대상을 가릴 때 씁니다.
 */
export const BACKSLASH_DRIVE_PATH = /^[a-z]:\\/i;
